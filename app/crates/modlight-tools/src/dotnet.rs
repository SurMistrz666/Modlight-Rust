//! .NET formatting the tools' texts need beyond `l10n::format`: custom date and time
//! patterns (`{1:yyyy-MM-dd 'at' HH:mm:ss 'UTC'}`) and the culture's default date-time
//! form (`DateTime.ToString()`).

use chrono::{DateTime, Datelike, TimeZone, Timelike};
use modlight_core::culture::Culture;
use modlight_core::l10n::{Arg, format};

/// A .NET custom date and time format (`yyyy`, `yy`, `MM`, `M`, `dd`, `d`, `HH`, `H`,
/// `hh`, `h`, `mm`, `m`, `ss`, `s`, `tt`, `'literal'`, `\x`).
pub fn custom<Tz: TimeZone>(pattern: &str, at: &DateTime<Tz>) -> String {
    let chars: Vec<char> = pattern.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if c == '\'' || c == '"' {
            let quote = c;
            i += 1;
            while i < chars.len() && chars[i] != quote {
                out.push(chars[i]);
                i += 1;
            }
            i += 1;
            continue;
        }
        if c == '\\' {
            if let Some(next) = chars.get(i + 1) {
                out.push(*next);
            }
            i += 2;
            continue;
        }
        let mut run = 1;
        while i + run < chars.len() && chars[i + run] == c {
            run += 1;
        }
        let hour12 = {
            let h = at.hour() % 12;
            if h == 0 { 12 } else { h }
        };
        match c {
            'y' => {
                if run <= 2 {
                    out.push_str(&format!("{:0width$}", at.year() % 100, width = run));
                } else {
                    out.push_str(&format!("{:0width$}", at.year(), width = run));
                }
            }
            'M' => out.push_str(&format!("{:0width$}", at.month(), width = run.min(2))),
            'd' => out.push_str(&format!("{:0width$}", at.day(), width = run.min(2))),
            'H' => out.push_str(&format!("{:0width$}", at.hour(), width = run.min(2))),
            'h' => out.push_str(&format!("{:0width$}", hour12, width = run.min(2))),
            'm' => out.push_str(&format!("{:0width$}", at.minute(), width = run.min(2))),
            's' => out.push_str(&format!("{:0width$}", at.second(), width = run.min(2))),
            't' => {
                let ampm = if at.hour() < 12 { "AM" } else { "PM" };
                out.push_str(if run == 1 { &ampm[..1] } else { ampm });
            }
            other => {
                for _ in 0..run {
                    out.push(other);
                }
            }
        }
        i += run;
    }
    out
}

/// `string.Format` with a date placeholder at `date_index` (`{n:pattern}`, or the
/// culture's general form without a pattern) and the other arguments as `l10n::format`
/// fills them.
pub fn format_with_date<Tz: TimeZone>(
    template: &str,
    date_index: usize,
    at: DateTime<Tz>,
    args: &[Arg],
) -> String {
    let open = format!("{{{date_index}");
    let mut text = template.to_string();
    if let Some(start) = text.find(&open) {
        let rest = &text[start + open.len()..];
        if let Some(close) = rest.find('}') {
            let inside = &rest[..close];
            let formatted = match inside.strip_prefix(':') {
                Some(pattern) => custom(pattern, &at),
                None => general(&at),
            };
            let end = start + open.len() + close + 1;
            text.replace_range(start..end, &formatted.replace('{', "{{").replace('}', "}}"));
        }
    }
    let mut padded: Vec<Arg> = args.to_vec();
    while padded.len() <= date_index {
        padded.push(Arg::from(""));
    }
    format(&text, &padded)
}

/// `DateTime.ToString()`: the culture's short date and long time ("G").
pub fn general<Tz: TimeZone>(at: &DateTime<Tz>) -> String {
    let culture = Culture::current();
    if culture.decimal == ',' {
        custom("dd.MM.yyyy HH:mm:ss", at)
    } else {
        custom("M/d/yyyy h:mm:ss tt", at)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::Utc;
    use modlight_core::culture::set_thread_culture;

    #[test]
    fn patterns() {
        let at = Utc.with_ymd_and_hms(2026, 3, 4, 5, 6, 7).unwrap();
        assert_eq!(
            custom("yyyy-MM-dd 'at' HH:mm:ss 'UTC'", &at),
            "2026-03-04 at 05:06:07 UTC"
        );
        assert_eq!(custom("d/M/yy h:m:s tt", &at), "4/3/26 5:6:7 AM");
        assert_eq!(custom("HH\\h", &at), "05h");
        assert_eq!(
            format_with_date(
                "Generated by {0} on {1:yyyy-MM-dd}",
                1,
                at,
                &[Arg::from("X")]
            ),
            "Generated by X on 2026-03-04"
        );
        assert_eq!(
            format_with_date(
                "On {0:yyyy}. From: {1}",
                0,
                at,
                &[Arg::from(""), Arg::from("u")]
            ),
            "On 2026. From: u"
        );
        set_thread_culture(Some(Culture::polish()));
        assert_eq!(general(&at), "04.03.2026 05:06:07");
        set_thread_culture(Some(Culture::english()));
        assert_eq!(general(&at), "3/4/2026 5:06:07 AM");
        set_thread_culture(None);
    }
}
